// create_csr_manual.cpp -- interactively asks for matrix A's size AND
// values (typed by hand), then matrix H's values, converts A into CSR
// format, and writes everything to csr_output_manual/.
//
// NEW in this version:
//   * Values are converted to Q8.8 fixed-point (16-bit signed).
//   * .mif files are written directly, ready for Quartus:
//         val.mif, col_idx.mif, row_ptr.mif, H.mif
//   * expected_out_q88.txt holds the golden result computed the SAME way
//     the hardware will (so your testbench comparison matches exactly).
//
// Compile:  g++ -std=c++11 -O2 create_csr_manual.cpp -o create_csr_manual
// Run:      ./create_csr_manual

#include <iostream>
#include <fstream>
#include <vector>
#include <string>
#include <cmath>
#include <cstdint>
#include <cstdlib>
#include <iomanip>

#ifdef _WIN32
    #include <direct.h>
#else
    #include <sys/stat.h>
#endif

using Matrix = std::vector<std::vector<double>>;

static void make_dir(const std::string& path) {
#ifdef _WIN32
    _mkdir(path.c_str());
#else
    mkdir(path.c_str(), 0755);
#endif
}

// ---------------------------------------------------------------
// Q8.8 fixed-point helpers
// ---------------------------------------------------------------
static bool overflow_warned = false;

// decimal -> Q8.8 (signed 16-bit). Example: 1.0 -> 256, 0.5 -> 128
static int16_t to_q8_8(double x) {
    long v = std::lround(x * 256.0);
    if (v > 32767 || v < -32768) {
        if (!overflow_warned) {
            std::cerr << "WARNING: value " << x
                      << " is outside the Q8.8 range (-128 to +127.99). "
                         "It will be clamped.\n";
            overflow_warned = true;
        }
        v = (v > 32767) ? 32767 : -32768;
    }
    return (int16_t)v;
}

// Q8.8 -> decimal (only for printing/checking)
static double from_q8_8(int16_t q) { return q / 256.0; }

// How many bits are needed to store values 0..max_value
static int bits_needed(int max_value) {
    int b = 1;
    while ((1 << b) <= max_value) b++;
    return b;
}

// ---------------------------------------------------------------
// MIF writer
//   data  : values to store (already integers; negatives allowed)
//   width : bits per word
// ---------------------------------------------------------------
static void write_mif(const std::string& path, const std::vector<int>& data, int width) {
    std::vector<int> d = data;
    if (d.empty()) d.push_back(0);          // MIF depth must be >= 1

    int hex_digits = (width + 3) / 4;
    uint32_t mask = (width >= 32) ? 0xFFFFFFFFu : ((1u << width) - 1u);

    std::ofstream f(path);
    f << "-- Auto-generated by create_csr_manual.cpp\n";
    f << "DEPTH = " << d.size() << ";\n";
    f << "WIDTH = " << width << ";\n";
    f << "ADDRESS_RADIX = HEX;\n";
    f << "DATA_RADIX = HEX;\n";
    f << "CONTENT BEGIN\n";
    for (size_t i = 0; i < d.size(); i++) {
        uint32_t word = ((uint32_t)d[i]) & mask;   // two's complement for negatives
        f << "    " << std::hex << std::uppercase << i << " : "
          << std::setw(hex_digits) << std::setfill('0') << word << ";\n"
          << std::dec << std::setfill(' ');
    }
    f << "END;\n";
}

// Prompts for an r x c matrix, one row at a time, space-separated values.
static Matrix read_matrix_interactive(int rows, int cols, const std::string& name) {
    Matrix M(rows, std::vector<double>(cols));
    std::cout << "\nEnter matrix " << name << " (" << rows << "x" << cols
              << "), one row at a time, " << cols << " space-separated values per row:\n";
    for (int i = 0; i < rows; i++) {
        std::cout << "Row " << i << ": ";
        for (int j = 0; j < cols; j++) {
            if (!(std::cin >> M[i][j])) {
                std::cerr << "Error: invalid input while reading " << name << ".\n";
                exit(1);
            }
        }
    }
    return M;
}

int main() {
    // ---- Step 1: ask for matrix A's size ----
    int a_rows, a_cols;
    std::cout << "Enter number of rows (m) for matrix A: ";
    std::cin >> a_rows;
    std::cout << "Enter number of columns (n) for matrix A: ";
    std::cin >> a_cols;

    if (a_rows <= 0 || a_cols <= 0) {
        std::cerr << "Error: matrix dimensions must be positive.\n";
        return 1;
    }

    // ---- Step 2: ask for matrix A's values (typed by hand) ----
    Matrix A = read_matrix_interactive(a_rows, a_cols, "A");

    // ---- Step 3: H's row count must match A's columns; column fixed at 1 ----
    int h_rows = a_cols;
    int h_cols = 1;
    std::cout << "\n(H will have " << h_rows << " rows and 1 column, to match A)\n";

    // ---- Step 4: ask for matrix H's values (typed by hand) ----
    Matrix H = read_matrix_interactive(h_rows, h_cols, "H");

    // ---- Convert A into CSR format (row_ptr, col_idx, val), skipping zeros ----
    std::vector<int> row_ptr(a_rows + 1, 0);
    std::vector<int> col_idx;
    std::vector<double> val;

    for (int i = 0; i < a_rows; i++) {
        for (int j = 0; j < a_cols; j++) {
            if (A[i][j] != 0.0) {
                col_idx.push_back(j);
                val.push_back(A[i][j]);
            }
        }
        row_ptr[i + 1] = (int)col_idx.size();
    }

    // ---- Compute Z = A @ H directly in decimal (original golden result) ----
    Matrix Z(a_rows, std::vector<double>(h_cols, 0.0));
    for (int i = 0; i < a_rows; i++) {
        for (int k = row_ptr[i]; k < row_ptr[i + 1]; k++) {
            int j = col_idx[k];
            double v = val[k];
            for (int f = 0; f < h_cols; f++) {
                Z[i][f] += v * H[j][f];
            }
        }
    }

    // ---- Convert val and H to Q8.8 ----
    std::vector<int16_t> val_q(val.size());
    for (size_t k = 0; k < val.size(); k++) val_q[k] = to_q8_8(val[k]);

    std::vector<int16_t> H_q(h_rows);
    for (int j = 0; j < h_rows; j++) H_q[j] = to_q8_8(H[j][0]);

    // ---- Fixed-point golden result: EXACTLY what the hardware will do ----
    //   product = (val * x) >> 8     (32-bit product, shift back to Q8.8)
    //   sum     = sum + product
    std::vector<int16_t> Z_q(a_rows, 0);
    for (int i = 0; i < a_rows; i++) {
        int32_t sum = 0;
        for (int k = row_ptr[i]; k < row_ptr[i + 1]; k++) {
            int32_t prod = (int32_t)val_q[k] * (int32_t)H_q[col_idx[k]];
            sum += (prod >> 8);
        }
        Z_q[i] = (int16_t)sum;
    }

    // ---- Write output files ----
    std::string out_dir = "csr_output_manual";
    make_dir(out_dir);

    // ---------- original text files (unchanged) ----------
    {
        std::ofstream f(out_dir + "/row_ptr.txt");
        for (int x : row_ptr) f << x << "\n";
    }
    {
        std::ofstream f(out_dir + "/col_idx.txt");
        for (int x : col_idx) f << x << "\n";
    }
    {
        std::ofstream f(out_dir + "/val.txt");
        f.precision(6);
        f << std::fixed;
        for (double x : val) f << x << "\n";
    }
    {
        std::ofstream f(out_dir + "/H.txt");
        f.precision(6);
        f << std::fixed;
        for (auto& row : H) {
            for (size_t j = 0; j < row.size(); j++) {
                f << row[j];
                if (j + 1 < row.size()) f << " ";
            }
            f << "\n";
        }
    }
    {
        std::ofstream f(out_dir + "/expected_out.txt");
        f.precision(6);
        f << std::fixed;
        for (auto& row : Z) {
            for (size_t j = 0; j < row.size(); j++) {
                f << row[j];
                if (j + 1 < row.size()) f << " ";
            }
            f << "\n";
        }
    }

    // ---------- NEW: MIF files for Quartus ----------
    int col_bits = bits_needed(a_cols - 1);                 // holds 0..n-1
    int ptr_bits = bits_needed((int)val.size());            // holds 0..nnz

    std::vector<int> val_words(val_q.begin(), val_q.end());
    std::vector<int> h_words(H_q.begin(), H_q.end());

    write_mif(out_dir + "/val.mif",     val_words, 16);
    write_mif(out_dir + "/H.mif",       h_words,   16);
    write_mif(out_dir + "/col_idx.mif", col_idx,   col_bits);
    write_mif(out_dir + "/row_ptr.mif", row_ptr,   ptr_bits);

    // ---------- NEW: expected output in Q8.8 (hex + decimal, for the testbench) ----------
    {
        std::ofstream f(out_dir + "/expected_out_q88.txt");
        f << "# row : hex(Q8.8) : decimal\n";
        for (int i = 0; i < a_rows; i++) {
            uint16_t w = (uint16_t)Z_q[i];
            f << i << " : " << std::hex << std::uppercase << std::setw(4)
              << std::setfill('0') << w << std::dec << std::setfill(' ')
              << " : " << std::fixed << std::setprecision(6) << from_q8_8(Z_q[i]) << "\n";
        }
    }
    {
        // plain hex only, one per line -- easy for $readmemh in a testbench
        std::ofstream f(out_dir + "/expected_out_q88.hex");
        for (int i = 0; i < a_rows; i++) {
            f << std::hex << std::uppercase << std::setw(4) << std::setfill('0')
              << (uint16_t)Z_q[i] << "\n";
        }
    }

    // ---- Summary ----
    std::cout << "\nWrote files to " << out_dir << "/:\n"
              << "  A is " << a_rows << "x" << a_cols
              << ", non-zero entries (nnz) = " << val.size() << "\n"
              << "  H is " << h_rows << "x" << h_cols << "\n"
              << "  Text : row_ptr.txt, col_idx.txt, val.txt, H.txt, expected_out.txt\n"
              << "  MIF  : val.mif (16-bit), H.mif (16-bit), col_idx.mif ("
              << col_bits << "-bit), row_ptr.mif (" << ptr_bits << "-bit)\n"
              << "  Test : expected_out_q88.txt, expected_out_q88.hex\n";

    std::cout << "\nQ8.8 check (decimal result vs fixed-point result):\n";
    for (int i = 0; i < a_rows; i++) {
        std::cout << "  y[" << i << "] = " << std::fixed << std::setprecision(6)
                  << Z[i][0] << "  ->  " << from_q8_8(Z_q[i]) << "\n";
    }

    return 0;
}