#!/usr/bin/env python3
"""
gen_hdl.py -- reads the MIF files made by create_csr_auto.cpp and writes
the Verilog that depends on matrix SIZE, so you never re-run the
MegaWizard or edit bit widths by hand.

Usage:   python3 gen_hdl.py spmv_50x50
         (normally called for you by txt_to_mif.py)

Number format: if <dir>/spmv_format.cfg exists it is used (written by
txt_to_mif.py), otherwise Q8.8 is assumed (FRAC=8, OUT_W=16).

Reads :  <dir>/val.mif  col_idx.mif  row_ptr.mif  H.mif
Writes:  <dir>/val_rom.v  col_idx_rom.v  row_ptr_rom.v  h_rom.v
         <dir>/spmv_top.v        (widths + FSM parameters filled in)
         <dir>/spmv_top_tb.v     (self-checking, reads expected_out_q88.hex)

spmv_fsm.v is NOT generated: it is fully parameterized and never changes.
"""
import os
import re
import sys


def read_mif_header(path):
    depth = width = None
    with open(path) as f:
        for line in f:
            m = re.match(r"\s*DEPTH\s*=\s*(\d+)", line, re.I)
            if m:
                depth = int(m.group(1))
            m = re.match(r"\s*WIDTH\s*=\s*(\d+)", line, re.I)
            if m:
                width = int(m.group(1))
            if depth and width:
                break
    if depth is None or width is None:
        sys.exit("Could not read DEPTH/WIDTH from " + path)
    return depth, width


def addr_bits(words):
    """Address width the MegaWizard picks: ceil(log2(words)), minimum 1."""
    b = 1
    while (1 << b) < words:
        b += 1
    return b


ROM_TEMPLATE = """// @NAME@.v  --  ROM: 1-PORT, @WORDS@ words x @W@ bits, init from @MIF@
// GENERATED by gen_hdl.py (same structure the MegaWizard produces:
// registered address, UNREGISTERED output).
// Do not open in the MegaWizard. To change sizes, re-run gen_hdl.py.

// synopsys translate_off
`timescale 1 ps / 1 ps
// synopsys translate_on
module @NAME@ (
    address,
    clock,
    q);

    input    [@AWM1@:0]  address;
    input      clock;
    output    [@WM1@:0]  q;
`ifndef ALTERA_RESERVED_QIS
// synopsys translate_off
`endif
    tri1      clock;
`ifndef ALTERA_RESERVED_QIS
// synopsys translate_on
`endif

    wire [@WM1@:0] sub_wire0;
    wire [@WM1@:0] q = sub_wire0[@WM1@:0];

    altsyncram    altsyncram_component (
                .address_a (address),
                .clock0 (clock),
                .q_a (sub_wire0),
                .aclr0 (1'b0),
                .aclr1 (1'b0),
                .address_b (1'b1),
                .addressstall_a (1'b0),
                .addressstall_b (1'b0),
                .byteena_a (1'b1),
                .byteena_b (1'b1),
                .clock1 (1'b1),
                .clocken0 (1'b1),
                .clocken1 (1'b1),
                .clocken2 (1'b1),
                .clocken3 (1'b1),
                .data_a ({@W@{1'b1}}),
                .data_b (1'b1),
                .eccstatus (),
                .q_b (),
                .rden_a (1'b1),
                .rden_b (1'b1),
                .wren_a (1'b0),
                .wren_b (1'b0));
    defparam
        altsyncram_component.address_aclr_a = "NONE",
        altsyncram_component.clock_enable_input_a = "BYPASS",
        altsyncram_component.clock_enable_output_a = "BYPASS",
        altsyncram_component.init_file = "@MIF@",
        altsyncram_component.intended_device_family = "Cyclone IV E",
        altsyncram_component.lpm_hint = "ENABLE_RUNTIME_MOD=NO",
        altsyncram_component.lpm_type = "altsyncram",
        altsyncram_component.numwords_a = @WORDS@,
        altsyncram_component.operation_mode = "ROM",
        altsyncram_component.outdata_aclr_a = "NONE",
        altsyncram_component.outdata_reg_a = "UNREGISTERED",
        altsyncram_component.widthad_a = @AW@,
        altsyncram_component.width_a = @W@,
        altsyncram_component.width_byteena_a = 1;

endmodule
"""

TOP_TEMPLATE = """// spmv_top.v -- GENERATED by gen_hdl.py for a @ROWS@ x @COLS@ matrix, nnz = @NNZ@
// Instantiates the 4 ROMs and the FSM and wires them together.

module spmv_top (
    input              clock,
    input              reset,   // synchronous, active high
    input              start,   // pulse high 1 cycle to begin
    output             done,
    output             y_valid,
    output [@RIW1@:0]  y_addr,
    output signed [@OUTW1@:0] y_out
);

    wire [@RPAW1@:0]   row_ptr_addr;
    wire [@KW1@:0]     row_ptr_q;

    wire [@NNZAW1@:0]  val_addr;
    wire signed [15:0] val_q;

    wire [@NNZAW1@:0]  col_addr;
    wire [@HAW1@:0]    col_q;

    wire [@HAW1@:0]    h_addr;
    wire signed [15:0] h_q;

    row_ptr_rom u_row_ptr_rom (.address (row_ptr_addr), .clock (clock), .q (row_ptr_q));
    val_rom     u_val_rom     (.address (val_addr),     .clock (clock), .q (val_q));
    col_idx_rom u_col_idx_rom (.address (col_addr),     .clock (clock), .q (col_q));
    h_rom       u_h_rom       (.address (h_addr),       .clock (clock), .q (h_q));

    spmv_fsm #(
        .NUM_ROWS   (@ROWS@),
        .ROW_IDX_W  (@RIW@),
        .K_W        (@KW@),
        .ROW_PTR_AW (@RPAW@),
        .NNZ_AW     (@NNZAW@),
        .H_AW       (@HAW@),
        .DATA_W     (16),
        .OUT_W      (@OUTW@),
        .FRAC       (@FRAC@)
    ) u_spmv_fsm (
        .clock        (clock),
        .reset        (reset),
        .start        (start),
        .done         (done),
        .y_valid      (y_valid),
        .y_addr       (y_addr),
        .y_out        (y_out),
        .row_ptr_addr (row_ptr_addr),
        .row_ptr_q    (row_ptr_q),
        .val_addr     (val_addr),
        .val_q        (val_q),
        .col_addr     (col_addr),
        .col_q        (col_q),
        .h_addr       (h_addr),
        .h_q          (h_q)
    );

endmodule
"""

TB_TEMPLATE = """`timescale 1ns/1ps
// spmv_top_tb.v -- GENERATED by gen_hdl.py. Self-checking testbench.
// Reads the golden results from @EXPFILE@ (run Questa
// from the folder that contains that file) and checks every y[i].
module spmv_top_tb;
    localparam NUM_ROWS = @ROWS@;

    reg  clock = 0;
    reg  reset = 1;
    reg  start = 0;
    wire done;
    wire y_valid;
    wire [@RIW1@:0] y_addr;
    wire signed [@OUTW1@:0] y_out;

    reg [@OUTW1@:0] expected [0:NUM_ROWS-1];
    integer pass_count = 0;
    integer fail_count = 0;

    spmv_top uut (
        .clock   (clock),
        .reset   (reset),
        .start   (start),
        .done    (done),
        .y_valid (y_valid),
        .y_addr  (y_addr),
        .y_out   (y_out)
    );

    always #5 clock = ~clock;   // 100 MHz

    initial begin
        $readmemh("@EXPFILE@", expected);

        repeat (3) @(posedge clock);
        reset = 0;
        @(posedge clock);

        start = 1;
        @(posedge clock);
        start = 0;

        wait (done == 1);
        #50;
        $display("-------------------------------------------------");
        $display("SUMMARY: %0d PASS, %0d FAIL, out of %0d rows", pass_count, fail_count, NUM_ROWS);
        if (pass_count == NUM_ROWS && fail_count == 0)
            $display("ALL TESTS PASSED");
        else
            $display("TEST FAILED");
        $display("-------------------------------------------------");
        $finish;
    end

    // watchdog: stop if the design never finishes
    initial begin
        #@TIMEOUT@;
        $display("TIMEOUT: design did not finish");
        $finish;
    end

    // check each y as it is produced
    always @(posedge clock) begin
        if (y_valid) begin
            if (y_out === expected[y_addr]) begin
                pass_count = pass_count + 1;
                $display("y[%0d] = %h (%0d)  PASS", y_addr, y_out, y_out);
            end else begin
                fail_count = fail_count + 1;
                $display("y[%0d] = %h (%0d)  FAIL (expected %h)", y_addr, y_out, y_out, expected[y_addr]);
            end
        end
    end
endmodule
"""


def fill(template, **kw):
    for k, v in kw.items():
        template = template.replace("@" + k + "@", str(v))
    return template


def read_cfg(d):
    cfg = {"FRAC": "8", "OUT_W": "16", "EXPECTED": "expected_out_q88.hex"}
    p = os.path.join(d, "spmv_format.cfg")
    if os.path.exists(p):
        for line in open(p):
            if "=" in line:
                k, v = line.strip().split("=", 1)
                cfg[k.strip()] = v.strip()
    return cfg["FRAC"], int(cfg["OUT_W"]), cfg["EXPECTED"]


def generate(d):
    frac, out_w, exp_file = read_cfg(d)

    val_d, val_w = read_mif_header(os.path.join(d, "val.mif"))
    col_d, col_w = read_mif_header(os.path.join(d, "col_idx.mif"))
    rp_d, rp_w = read_mif_header(os.path.join(d, "row_ptr.mif"))
    h_d, h_w = read_mif_header(os.path.join(d, "H.mif"))

    # ---- consistency checks ----
    if val_w != 16 or h_w != 16:
        sys.exit("val.mif and H.mif must be 16 bits wide.")
    if val_d != col_d:
        sys.exit("val.mif and col_idx.mif must have the same DEPTH (= nnz).")

    nnz = val_d
    rows = rp_d - 1
    cols = h_d

    nnz_aw = addr_bits(nnz)
    rp_aw = addr_bits(rp_d)
    h_aw = addr_bits(h_d)
    row_idx_w = addr_bits(rows)
    if col_w != h_aw:
        sys.exit("col_idx width (%d) must equal H address width (%d)." % (col_w, h_aw))

    # ---- ROM files ----
    roms = [
        ("val_rom", "val.mif", val_d, val_w, nnz_aw),
        ("col_idx_rom", "col_idx.mif", col_d, col_w, nnz_aw),
        ("row_ptr_rom", "row_ptr.mif", rp_d, rp_w, rp_aw),
        ("h_rom", "H.mif", h_d, h_w, h_aw),
    ]
    for name, mif, words, w, aw in roms:
        text = fill(ROM_TEMPLATE, NAME=name, MIF=mif, WORDS=words, W=w, WM1=w - 1,
                    AW=aw, AWM1=aw - 1)
        with open(os.path.join(d, name + ".v"), "w") as f:
            f.write(text)

    # ---- top level ----
    top = fill(TOP_TEMPLATE, ROWS=rows, COLS=cols, NNZ=nnz,
               RIW=row_idx_w, RIW1=row_idx_w - 1,
               KW=rp_w, KW1=rp_w - 1,
               RPAW=rp_aw, RPAW1=rp_aw - 1,
               NNZAW=nnz_aw, NNZAW1=nnz_aw - 1,
               HAW=h_aw, HAW1=h_aw - 1,
               OUTW=out_w, OUTW1=out_w - 1, FRAC=frac)
    with open(os.path.join(d, "spmv_top.v"), "w") as f:
        f.write(top)

    # ---- testbench ----
    # worst case ~8 cycles per row + ~8 per non-zero, 10 ns per cycle, x3 margin
    timeout_ns = (rows * 8 + nnz * 8 + 200) * 10 * 3
    tb = fill(TB_TEMPLATE, ROWS=rows, RIW1=row_idx_w - 1, TIMEOUT=timeout_ns,
              OUTW1=out_w - 1, EXPFILE=exp_file)
    with open(os.path.join(d, "spmv_top_tb.v"), "w") as f:
        f.write(tb)

    print("Matrix: %d rows x %d cols, nnz = %d" % (rows, cols, nnz))
    print("Generated in %s/ :" % d)
    print("  val_rom.v      %5d words x %2d bits (address %d bits)" % (val_d, val_w, nnz_aw))
    print("  col_idx_rom.v  %5d words x %2d bits (address %d bits)" % (col_d, col_w, nnz_aw))
    print("  row_ptr_rom.v  %5d words x %2d bits (address %d bits)" % (rp_d, rp_w, rp_aw))
    print("  h_rom.v        %5d words x %2d bits (address %d bits)" % (h_d, h_w, h_aw))
    print("  spmv_top.v, spmv_top_tb.v")
    print("FSM parameters used: NUM_ROWS=%d ROW_IDX_W=%d K_W=%d ROW_PTR_AW=%d NNZ_AW=%d H_AW=%d"
          % (rows, row_idx_w, rp_w, rp_aw, nnz_aw, h_aw))
    print("Number format: FRAC=%s OUT_W=%d  (testbench reads %s)" % (frac, out_w, exp_file))


def main():
    if len(sys.argv) != 2:
        sys.exit("Usage: python3 gen_hdl.py <folder with the .mif files>")
    generate(sys.argv[1])


if __name__ == "__main__":
    main()
