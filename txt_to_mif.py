#!/usr/bin/env python3
"""
txt_to_mif.py -- turns the .txt files from YOUR existing generator
(create_csr_interactive / create_csr_manual) into everything Quartus needs.

Usage:   python3 txt_to_mif.py <folder with the .txt files> <output folder>
  e.g.   python3 txt_to_mif.py csr_output spmv_50x50

Reads :  row_ptr.txt  col_idx.txt  val.txt  H.txt   (expected_out.txt if present)

Number format is chosen automatically:
  * all values are whole numbers that fit 16-bit signed  -> INTEGER mode
        val/H = 16-bit signed, products/sums = 32-bit, no shift, y = 32-bit
  * otherwise, all values inside -128 .. +127.99          -> Q8.8 mode
        val/H = round(x*256), (val*H)>>8 per product, y = 16-bit
  * otherwise -> error (value range not supported)

Writes into <output folder>:
  val.mif  col_idx.mif  row_ptr.mif  H.mif
  expected_out_int.hex  (or expected_out_q88.hex)   golden results for the testbench
  spmv_format.cfg
  val_rom.v col_idx_rom.v row_ptr_rom.v h_rom.v spmv_top.v spmv_top_tb.v  (via gen_hdl)
"""
import os
import sys

import gen_hdl


def read_numbers(path):
    if not os.path.exists(path):
        sys.exit("Missing file: " + path)
    out = []
    with open(path) as f:
        for line in f:
            for tok in line.split():
                out.append(float(tok))
    return out


def bits_needed(max_value):
    b = 1
    while (1 << b) <= max_value:
        b += 1
    return b


def write_mif(path, data, width):
    if not data:
        data = [0]
    mask = (1 << width) - 1
    digits = (width + 3) // 4
    with open(path, "w") as f:
        f.write("-- Auto-generated by txt_to_mif.py\n")
        f.write("DEPTH = %d;\nWIDTH = %d;\n" % (len(data), width))
        f.write("ADDRESS_RADIX = HEX;\nDATA_RADIX = HEX;\nCONTENT BEGIN\n")
        for i, v in enumerate(data):
            f.write("    %X : %0*X;\n" % (i, digits, v & mask))
        f.write("END;\n")


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    src, dst = sys.argv[1], sys.argv[2]
    os.makedirs(dst, exist_ok=True)

    row_ptr = [int(round(x)) for x in read_numbers(os.path.join(src, "row_ptr.txt"))]
    col_idx = [int(round(x)) for x in read_numbers(os.path.join(src, "col_idx.txt"))]
    val = read_numbers(os.path.join(src, "val.txt"))
    H = read_numbers(os.path.join(src, "H.txt"))

    rows, cols, nnz = len(row_ptr) - 1, len(H), len(val)

    # ---- sanity checks on the CSR data ----
    if len(col_idx) != nnz:
        sys.exit("col_idx.txt has %d entries but val.txt has %d" % (len(col_idx), nnz))
    if row_ptr[0] != 0 or row_ptr[-1] != nnz:
        sys.exit("row_ptr.txt must start at 0 and end at nnz=%d (got %d..%d)"
                 % (nnz, row_ptr[0], row_ptr[-1]))
    if any(row_ptr[i] > row_ptr[i + 1] for i in range(rows)):
        sys.exit("row_ptr.txt must be non-decreasing")
    if any(c < 0 or c >= cols for c in col_idx):
        sys.exit("col_idx.txt has an index outside 0..%d (H.txt has %d entries)" % (cols - 1, cols))

    # ---- choose the number format ----
    allv = val + H
    all_int = all(abs(x - round(x)) < 1e-9 for x in allv)
    if all_int and all(-32768 <= round(x) <= 32767 for x in allv):
        mode = "int"
        val_w = [int(round(x)) for x in val]
        h_w = [int(round(x)) for x in H]
        frac, out_w = 0, 32
        exp_file = "expected_out_int.hex"
    elif all(-128.0 <= x < 128.0 for x in allv):
        mode = "q88"
        val_w = [int(round(x * 256)) for x in val]
        h_w = [int(round(x * 256)) for x in H]
        frac, out_w = 8, 16
        exp_file = "expected_out_q88.hex"
    else:
        sys.exit("Values not supported: need whole numbers within +-32767, "
                 "or decimals within -128..127.99 (largest |value| = %g)" % max(abs(x) for x in allv))

    # ---- hardware-exact golden result ----
    golden = []
    exact = []
    for i in range(rows):
        s = 0
        e = 0.0
        for k in range(row_ptr[i], row_ptr[i + 1]):
            s += (val_w[k] * h_w[col_idx[k]]) >> frac     # arithmetic shift, like >>> in Verilog
            e += val[k] * H[col_idx[k]]
        exact.append(e)
        golden.append(s)
    lim = 1 << (out_w - 1)
    bad = [i for i, g in enumerate(golden) if not -lim <= g < lim]
    if bad:
        sys.exit("Row(s) %s overflow the %d-bit output." % (bad[:5], out_w))

    # ---- write MIFs ----
    col_bits = bits_needed(cols - 1)
    ptr_bits = bits_needed(nnz)
    write_mif(os.path.join(dst, "val.mif"), val_w, 16)
    write_mif(os.path.join(dst, "H.mif"), h_w, 16)
    write_mif(os.path.join(dst, "col_idx.mif"), col_idx, col_bits)
    write_mif(os.path.join(dst, "row_ptr.mif"), row_ptr, ptr_bits)

    digits = out_w // 4
    mask = (1 << out_w) - 1
    with open(os.path.join(dst, exp_file), "w") as f:
        for g in golden:
            f.write("%0*X\n" % (digits, g & mask))
    with open(os.path.join(dst, "expected_out_readable.txt"), "w") as f:
        f.write("# row : hex : decimal\n")
        for i, g in enumerate(golden):
            f.write("%d : %0*X : %d\n" % (i, digits, g & mask, g))
    with open(os.path.join(dst, "spmv_format.cfg"), "w") as f:
        f.write("MODE=%s\nFRAC=%d\nOUT_W=%d\nEXPECTED=%s\n" % (mode, frac, out_w, exp_file))

    # ---- report ----
    print("Read %s/: %d rows x %d cols, nnz = %d" % (src, rows, cols, nnz))
    print("Number format chosen: %s  (val/H 16-bit signed, y %d-bit, FRAC=%d)"
          % ("INTEGER" if mode == "int" else "Q8.8", out_w, frac))
    print("Largest |val| = %g, largest |H| = %g, largest |y| = %d"
          % (max(abs(x) for x in val), max(abs(x) for x in H), max(abs(g) for g in golden)))

    # cross-check against the generator's own expected_out.txt
    ep = os.path.join(src, "expected_out.txt")
    if os.path.exists(ep):
        theirs = read_numbers(ep)
        if len(theirs) == rows and all(abs(a - b) <= 0.01 * max(1.0, abs(a)) for a, b in zip(theirs, exact)):
            print("Cross-check: matches your generator's expected_out.txt  [OK]")
        else:
            print("WARNING: does NOT match your generator's expected_out.txt "
                  "(check that H.txt/val.txt are from the same run)")

    gen_hdl.generate(dst)
    print("\nDone. Copy ALL files from %s/ into C:\\SpMV_Project (keep spmv_fsm.v)." % dst)


if __name__ == "__main__":
    main()
